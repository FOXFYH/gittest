  // 0.12：语音播报——直接用浏览器本地 TTS 朗读卡片文本（本地识别，不依赖 AI、不写语音小卡片）
  function 朗读(文本) {
    var 文 = 文字(文本).trim();
    if (!文) { 提示('本卡没有可朗读的清单正文大白话'); return; }
    if (!global.speechSynthesis || typeof global.SpeechSynthesisUtterance !== 'function') {
      提示('本浏览器不支持语音播报');
      return;
    }
    try {
      global.speechSynthesis.cancel();
      var u = new global.SpeechSynthesisUtterance(文);
      u.lang = 'zh-CN';
      u.rate = 1.0;
      global.speechSynthesis.speak(u);
    } catch (e) { 提示('语音播报失败：' + ((e && e.message) || e)); }
  }

