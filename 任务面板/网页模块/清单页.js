  // 点小蓝卡 → 跳到那张卡（按编号前缀定层级，整页进入它的细分页）
  function 跳卡(号) {
    var 编 = String(号 || '').toUpperCase();
    if (!编) return;
    if (!有接口()) { 提示('接口未就绪'); return; }
    var 取件;
    var 前二 = 编.substr(0, 2);
    if (前二 === 'ST') {            // 系统清单的任务 ST<n>（必须先于 S 判断）
      取件 = global.接口.任务详情(编).then(function (r) { return r && r.任务 ? 任务节点(r.任务) : null; });
    } else if (前二 === 'SP') {     // 系统清单的小点 SP<n>
      取件 = global.接口.点详情(编).then(function (r) {
        return r && r.点 ? 点节点(r.点, 文字(r.点.父), 文字(r.点.任务)) : null;
      });
    } else if (编.charAt(0) === 'L' || 编.charAt(0) === 'S') {   // 本地清单 L / 系统清单 S
      取件 = global.接口.清单详情(编).then(function (r) { return r && r.清单 ? 清单节点(r.清单) : null; });
    } else if (编.charAt(0) === 'T') {
      取件 = global.接口.任务详情(编).then(function (r) { return r && r.任务 ? 任务节点(r.任务) : null; });
    } else {
      取件 = global.接口.点详情(编).then(function (r) {
        return r && r.点 ? 点节点(r.点, 文字(r.点.父), 文字(r.点.任务)) : null;
      });
    }
    取件.then(function (n) {
      if (!n) { 提示('找不到卡片：' + 编); return; }
      进节点(n, n.种 === '清单' ? 1 : (n.种 === '任务' ? 2 : 3));
    })['catch'](function (e) { 提示('打开卡片失败：' + ((e && e.message) || e)); });
  }

