原话目录名 = "02_原话流水账"


def 备注路径():
    """当前生效空间的 原话备注.json —— 调用时现算（P1-B-1 治 X1，不再 import 期定死）。"""
    return os.path.join(公共.取路径("数据目录"), "原话备注.json")


_表头字样 = ("#", "序号")


# ---------------------------------------------------------------- 路径

def 原话目录():
    """工作台根\\WorkBuddy总管文件夹\\02_原话流水账（跟着程序位置走，不写死盘符）"""
    工作台 = 公共.找工作台根()
    for 候选 in (
        os.path.join(工作台, "WorkBuddy总管文件夹", 原话目录名),
        os.path.join(工作台, 原话目录名),
    ):
        if os.path.isdir(候选):
            return 候选
    return os.path.join(工作台, "WorkBuddy总管文件夹", 原话目录名)


def 找表文件(日):
    目录 = 原话目录()
    for 名 in ("老板原话流水账_%s.md" % 日, "原话流水账_%s.md" % 日, "原话台账_%s.md" % 日):
        路径 = os.path.join(目录, 名)
        if os.path.isfile(路径):
            return 路径
    return ""


def 找素材文件(日):
    路径 = os.path.join(原话目录(), "原话素材_%s.md" % 日)
    return 路径 if os.path.isfile(路径) else ""


# ---------------------------------------------------------------- 读主表

def _切格(行):
    s = 行.strip()
    if not s.startswith("|"):
        return None
    格 = [c.strip() for c in s.strip("|").split("|")]
    return 格


def 读表(日):
    """返回 (行列表, 错误说明)。行 = {序号, 键, 时刻, 摘要, 派工单, 落实, 证据}
    只认 6 列数据行的主表，附录里的 4 列小表不计（那是缺口附表）。
    """
    路径 = 找表文件(日)
    if not 路径:
        return [], "未找到 %s 的流水账表文件" % 日
    try:
        with open(路径, "r", encoding="utf-8", errors="replace") as f:
            文本行 = f.read().splitlines()
    except Exception as 错:
        return [], "读表失败: %s" % 错

    结果 = []
    for 行 in 文本行:
        格 = _切格(行)
        if not 格 or len(格) < 6:
            continue
        序号 = 格[0]
        if 序号 in _表头字样 or set(序号) <= set("-: "):
            continue
        if not re.fullmatch(r"\d{1,3}", 序号):
            continue
        号 = int(序号)
        结果.append({
            "序号": "%03d" % 号,
            "键": "%s#%03d" % (日, 号),
            "时刻": 格[1],
            "摘要": 格[2],
            "派工单": 格[3],
            "落实": 格[4],
            "证据": 格[5],
        })
    return 结果, ""


def 读全文库(日):
    """从素材文件里取每条的完整正文；返回 {序号: 全文}"""
    结果 = {}
    路径 = 找素材文件(日)
    if not 路径:
        return 结果
    try:
        with open(路径, "r", encoding="utf-8", errors="replace") as f:
            文本 = f.read()
    except Exception:
        return 结果
    块们 = re.split(r"^##\s*第(\d+)条.*$", 文本, flags=re.M)
    # 切分后结构： [前言, 号1, 正文1, 号2, 正文2, ...]
    for i in range(1, len(块们) - 1, 2):
        号 = "%03d" % int(块们[i])
        正文 = 块们[i + 1].strip()
        if 正文:
            结果[号] = 正文
    return 结果


# ---------------------------------------------------------------- 备注库

def _空库():
    return {"版本": 1, "账号": "", "端点": "", "更新": 公共.现在全(), "条": {}}


def 读备注():
    数据 = 公共.读json(备注路径(), None)
    if not isinstance(数据, dict):
        return _空库()
    数据.setdefault("版本", 1)
    # P1-B-1（2-1b）：老文件没 账号/端点 也要读得进
    数据.setdefault("账号", "")
    数据.setdefault("端点", "")
    条 = 数据.get("条")
    if not isinstance(条, dict):
        数据["条"] = {}
    for 键, 值 in 数据["条"].items():
        if not isinstance(值, dict):
            数据["条"][键] = {}
            continue
        值.setdefault("备注", "")
        值.setdefault("关联卡", [])
        值.setdefault("备注人", "")
        值.setdefault("备注时间", "")
        值.setdefault("历史", [])
        if not isinstance(值["关联卡"], list):
            值["关联卡"] = []
    return 数据


def _写备注(数据):
    数据["版本"] = 1
    数据["账号"] = 公共.取路径("账号")
    数据["端点"] = 公共.取路径("端点")
    数据["更新"] = 公共.现在全()
    头 = {"版本": 数据["版本"], "账号": 数据["账号"],
          "端点": 数据["端点"], "更新": 数据["更新"]}
    for 键, 值 in list(数据.items()):
        if 键 not in 头:
            头[键] = 值
    数据.clear()
    数据.update(头)
    公共.原子写json(备注路径(), 数据)


def _条目(数据, 键):
    条 = 数据["条"]
    if 键 not in 条:
        条[键] = {"备注": "", "关联卡": [], "备注人": "", "备注时间": "", "历史": []}
    return 条[键]


def 写备注(键, 话, 谁="总管"):
    with 公共.文件锁(备注路径() + ".lock"):
        数据 = 读备注()
        条目 = _条目(数据, 键)
        原 = 条目.get("备注", "")
        条目["备注"] = (原 + "\n" + 话).strip() if 原 else 话
        条目["备注人"] = 谁
        条目["备注时间"] = 公共.现在秒()
        条目.setdefault("历史", []).append({"ts": 公共.现在秒(), "谁": 谁, "动作": "备注 新增"})
        _写备注(数据)
    return True, "已记备注"


def 关联卡(键, 卡id, 谁="总管"):
    卡id = (卡id or "").strip().upper()
    if not re.fullmatch(r"T\d{4}", 卡id):
        return False, "卡号格式不对：%s（应形如 T0042）" % 卡id
    卡们 = {卡.get("id"): 卡 for 卡 in 任务卡库.读().get("卡", [])}
    if 卡id not in 卡们:
        return False, "卡不存在：%s" % 卡id
    新关联 = False
    with 公共.文件锁(备注路径() + ".lock"):
        数据 = 读备注()
        条目 = _条目(数据, 键)
        已 = 条目.setdefault("关联卡", [])
        新关联 = 卡id not in 已
        if 新关联:
            已.append(卡id)
            if not 条目.get("备注人"):
                条目["备注人"] = 谁
            条目.setdefault("历史", []).append({"ts": 公共.现在秒(), "谁": 谁, "动作": "关联卡 → %s" % 卡id})
            _写备注(数据)
    # 【双向写·2026-10-27 制度锁配套】原话侧关联的同时，把键补进 卡.来源原话；
    # 旧版只写备注库一头，导致「已关联」却开单校验查不到（老板 10-27 发现并锁死）。
    # 幂等：就算备注库「本来就关联」，也会把缺失的卡侧补齐（修存量）。
    来源 = list(卡们[卡id].get("来源原话") or [])
    if 键 not in 来源:
        来源.append(键)
        卡好, 卡说 = 任务卡库.设来源原话(卡id, 来源, 谁=谁)
        if not 卡好:
            return False, "原话侧已写但卡侧写失败：%s（请手工 任务.关联原话 修复）" % 卡说
    return True, (("%s 已关联 %s" if 新关联 else "%s 本来就关联 %s（已补卡侧同步）") % (键, 卡id))


def 解除关联(键, 卡id, 谁="总管"):
    with 公共.文件锁(备注路径() + ".lock"):
        数据 = 读备注()
        条目 = _条目(数据, 键)
        已 = 条目.get("关联卡", [])
        if 卡id not in 已:
            return True, "未关联 %s，无需解除" % 卡id
        已.remove(卡id)
        条目.setdefault("历史", []).append({"ts": 公共.现在秒(), "谁": 谁, "动作": "解除关联 %s" % 卡id})
        _写备注(数据)
    return True, "%s 已解除关联 %s" % (键, 卡id)


# ---------------------------------------------------------------- 合并视图

def _灯(行, 卡们):
    """标色口径（2026-10-25 21:30 老板拍板，见 设计_v0.3 §2.5 第1条）：
    红＝派工单为空 或 含「待派」；灰＝「未派·闲聊无需派」（老板说了但没有交付物，属正常）；
    绿＝已关联任务卡；黄＝有派工单（含"已并入Pxx"）但还没落成卡。
    """
    派 = (行.get("派工单") or "").strip()
    if not 派 or ("待派" in 派):
        return "红"
    if 派.startswith("未派") and ("闲聊" in 派 or "无需派" in 派):
        return "灰"
    if not 卡们:
        return "黄"
    return "绿"


def 合并(日=None):
    """把 主表 + 备注库 + 任务卡 合成 P4 要显示的整表。
    返回 {"日":…, "条":[…], "统计":{…}, "错误":"", "表文件":…}
    """
    日 = 日 or 公共.今天前缀()
    行们, 错误 = 读表(日)
    备注库 = 读备注()
    卡表 = {卡.get("id"): 卡 for 卡 in 任务卡库.读().get("卡", [])}

    条们 = []
    for 行 in 行们:
        备注 = 备注库["条"].get(行["键"], {})
        卡ids = [i for i in 备注.get("关联卡", []) if i in 卡表]
        卡们 = [{"id": i, "标题": 卡表[i].get("标题", ""), "状态": 卡表[i].get("状态", "")} for i in 卡ids]
        条目 = dict(行)
        条目["备注"] = 备注.get("备注", "")
        条目["备注人"] = 备注.get("备注人", "")
        条目["备注时间"] = 备注.get("备注时间", "")
        条目["关联卡"] = 卡ids
        条目["卡"] = 卡们
        条目["灯"] = _灯(行, 卡ids)
        条目["已落实"] = bool(卡ids)
        条们.append(条目)

    return {
        "日": 日,
        "条": 条们,
        "统计": 统计(日, 条们),
        "错误": 错误,
        "表文件": 找表文件(日),
    }


def 统计(日=None, 条们=None):
    """原话统计（口径写在返回的 口径 字段里，便于对账）。

    未派口径（2026-10-25 21:30 老板拍板，别再用"含未派"做包含匹配）：
      未派 = 派工单列为空，或【含「待派」】——实测 9 条，只有这 9 条进红色横幅。
      「未派·闲聊无需派」单独计为 闲聊（53 条），不进红色横幅，只在灰字里报数。
      「未派·已并入Pxx」算已派（确实并进了某张派工单），并入未落成卡时标黄。
    """
    if 条们 is None:
        条们 = 合并(日)["条"]
    总 = len(条们)
    已派 = 0
    未派 = 0
    待派 = 0
    闲聊 = 0
    已验收 = 0
    有卡 = 0
    for 条 in 条们:
        派 = (条.get("派工单") or "").strip()
        if (not 派) or ("待派" in 派):
            未派 += 1
        elif 派.startswith("未派") and ("闲聊" in 派 or "无需派" in 派):
            闲聊 += 1
        else:
            已派 += 1
        if "待派" in 派:
            待派 += 1
        if (条.get("落实") or "") == "已验收":
            已验收 += 1
        if 条.get("关联卡"):
            有卡 += 1
    覆盖率 = round(已派 * 100.0 / 总, 1) if 总 else 0.0
    落实率 = round(有卡 * 100.0 / 总, 1) if 总 else 0.0
    return {
        "日": 日 or 公共.今天前缀(),
        "总数": 总,
        "已派": 已派,
        "未派": 未派,
        "待派": 待派,
        "闲聊": 闲聊,
        "已关联卡": 有卡,
        "已验收": 已验收,
        "覆盖率": 覆盖率,
        "落实率": 落实率,
        "口径": "未派＝派工单为空或含「待派」（只此两种）；闲聊无需派单列不计入未派；"
                "已派含「未派·已并入Pxx」；覆盖率＝已派/总数；落实率＝已关联任务卡/总数",
    }


def 取全文(日, 序号):
    return 读全文库(日).get("%03d" % int(序号), "")

