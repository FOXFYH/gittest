def _扫描Tk注册表():
    """真扫 Tk 壳源码里的 界面注册表（不是自己声明）。"""
    路径 = os.path.join(公共.程序根, "总管面板.pyw")
    if not os.path.isfile(路径):
        return [], "找不到 总管面板.pyw"
    try:
        with open(路径, "r", encoding="utf-8", errors="replace") as f:
            文本 = f.read()
    except Exception as 错:
        return [], "读 Tk 壳失败: %s" % 错
    位置 = 文本.find("界面注册表")
    if 位置 < 0:
        return [], "Tk 壳里没有 界面注册表 清单"
    段 = 文本[位置:]
    起 = 段.find("[")
    止 = 段.find("]", 起)
    if 起 < 0 or 止 < 0:
        return [], "界面注册表 不是列表字面量"
    import re
    return re.findall(r'"([^"]+)"', 段[起:止]), ""


def _取网页命令列表():
    """优先 HTTP 真探测 GET /api/cmd列表；服务没起就解析 HTML 里那份唯一数组。"""
    import re
    状态 = 采集器.读状态()
    端口 = 状态.get("网页端口", 0)
    if 端口:
        try:
            import urllib.parse
            import urllib.request
            网址 = "http://127.0.0.1:%d%s" % (int(端口),
                                            urllib.parse.quote("/api/cmd列表"))
            with urllib.request.urlopen(网址, timeout=2) as r:
                数据 = json.loads(r.read().decode("utf-8"))
            return 数据.get("命令", []), "HTTP"
        except Exception:
            pass
    路径 = os.path.join(公共.网页源目录, "总管面板.html")
    if not os.path.isfile(路径):
        return [], "缺少 网页端源文件\\总管面板.html"
    try:
        with open(路径, "r", encoding="utf-8", errors="replace") as f:
            文本 = f.read()
    except Exception:
        return [], "读网页源码失败"
    位置 = 文本.find("const 命令列表")
    if 位置 < 0:
        return [], "网页源码里没有 命令列表 数组"
    起 = 文本.find("[", 位置)
    止 = 文本.find("]", 起)
    return re.findall(r'"([^"]+)"', 文本[起:止]), "HTML（网页服务未起，读的是唯一源文件）"


def _cmd_系统对齐自检(参数, 来源):
    起点 = time.time()
    tk命令, tk错误 = _扫描Tk注册表()
    网页命令, 网页方式 = _取网页命令列表()
    缺 = []
    表 = []
    cli脚本 = os.path.join(公共.程序根, "总管面板CLI.py")

    for 项 in 命令表:
        名 = 项["命令"]
        # CLI：真跑子进程 --dry
        cli好 = False
        cli说明 = ""
        try:
            结果 = subprocess.run(
                [sys.executable, cli脚本, 名, "--dry", "--json"],
                capture_output=True, text=True, encoding="utf-8", errors="replace",
                timeout=25, creationflags=0x08000000, cwd=公共.程序根)
            出口 = 结果.returncode
            cli好 = (出口 == 0) and ('"ok": true' in (结果.stdout or "")
                                     or '"ok":true' in (结果.stdout or ""))
            cli说明 = "退出码 %d" % 出口
        except Exception as 错:
            cli说明 = "调用失败: %s" % 错
        tk好 = 名 in tk命令
        网页好 = 名 in 网页命令
        表.append({
            "命令": 名, "实现": True, "CLI": cli好, "Tk": tk好, "网页": 网页好,
            "读写": 项["读写"], "页": 项["页"], "说明": cli说明,
        })
        if not cli好:
            缺.append("%s：CLI 壳没调通（%s）→ 在 总管面板CLI.py 里放行该命令名" % (名, cli说明))
        if not tk好:
            缺.append("%s：Tk 壳未注册 → 往 总管面板.pyw 的 界面注册表 加一行" % 名)
        if not 网页好:
            缺.append("%s：网页端未声明 → 往 总管面板.html 的 const 命令列表 加一行" % 名)

    全绿 = not 缺
    return _成功({
        "表": 表,
        "缺": 缺,
        "RESULT": "PASS" if 全绿 else "FAIL",
        "Tk清单条数": len(tk命令),
        "网页清单条数": len(网页命令),
        "网页探测方式": 网页方式,
    }, "RESULT=%s（CLI/Tk/网页 三列逐条真探测）" % ("PASS" if 全绿 else "FAIL"),
        (time.time() - 起点) * 1000)


