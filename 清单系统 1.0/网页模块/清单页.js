  // 保存成功后对比新旧正文，找出本次「补号」的小绿卡行 → [{行, 卡号}]
  function 补号表(旧文, 新文) {
    function 各行号(文) {
      var 出 = [], 行们 = String(文 || '').split('\n');
      for (var i = 0; i < 行们.length; i++) {
        var m = 结构行正则.exec(行们[i]);
        if (m) 出.push({ 行: i + 1, 卡号: String(m[4] || '').trim().toUpperCase() });
      }
      return 出;
    }
    var 旧 = 各行号(旧文), 新 = 各行号(新文), 出 = [];
    for (var k = 0; k < 新.length && k < 旧.length; k++) {
      if (!旧[k].卡号 && 新[k].卡号) 出.push(新[k]);
    }
    return 出;
  }
