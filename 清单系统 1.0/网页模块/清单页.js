  function 平铺转树(列) {
    var 根 = [], 栈 = [];
    (列 || []).forEach(function (n) {
      var 节 = { 号: n.号, 题: n.题, 备注: n.备注, 层: n.层, 文: '', 子: [], 有子: !!n.有子 };
      while (栈.length && 栈[栈.length - 1].层 >= 节.层) 栈.pop();
      if (栈.length) 栈[栈.length - 1].子.push(节); else 根.push(节);
      栈.push(节);
    });
    return 根;
  }
